// ============ POSTS ============
export const loadChunksForPost = async (id: string, postData: any) => {
  if (postData.is_chunked) {
    try {
      let full_html = '';
      let full_html_hi = '';
      const chunkCount = postData.chunk_count || 0;
      
      if (chunkCount === 0) {
        // Fallback to legacy chunks if they exist (unlikely to have permissions though)
        try {
          const chunksSnap = await getDocs(query(collection(db, `posts/${id}/chunks`), orderBy('index')));
          chunksSnap.docs.forEach(doc => {
            const data = doc.data();
            if (data.html) full_html += data.html;
            if (data.html_hi) full_html_hi += data.html_hi;
          });
        } catch(e) { /* ignore fallback errors */ }
      } else {
        const promises = [];
        for (let i = 0; i < chunkCount; i++) {
          promises.push(getDoc(doc(db, 'posts', `${id}_chunk_${i}`)));
        }
        const snaps = await Promise.all(promises);
        snaps.forEach(snap => {
          if (snap.exists()) {
            const data = snap.data();
            if (data.html) full_html += data.html;
            if (data.html_hi) full_html_hi += data.html_hi;
          }
        });
      }
      
      postData.tables_html = full_html ? decompressHtml(full_html) : '';
      postData.tables_html_hi = full_html_hi ? decompressHtml(full_html_hi) : '';
    } catch(e) {
      console.error("Error loading chunks for post", id, e);
      postData.tables_html = '';
      postData.tables_html_hi = '';
    }
  } else {
    postData.tables_html = decompressHtml(postData.tables_html);
    postData.tables_html_hi = decompressHtml(postData.tables_html_hi);
  }
};

export const getPosts = async () => {
  const cached = getLocalAdminCache<any[]>('posts');
  if (cached && cached.length > 0) {
    return cached;
  }
  try {
    const q = query(collection(db, 'posts'));
    const snap = await getDocs(q);
    const posts = snap.docs
      .map(d => {
        const data = d.data() as Record<string, any>;
        return {
          id: d.id,
          ...data,
          tables_html: decompressHtml(data.tables_html),
          tables_html_hi: decompressHtml(data.tables_html_hi),
          created_at: data.created_at?.toDate?.()?.toISOString?.() || data.created_at || '',
          updated_at: data.updated_at?.toDate?.()?.toISOString?.() || data.updated_at || '',
        } as Record<string, any>;
      })
      .filter(p => !p.id.includes('_chunk_') && p.name_of_post);
    
    // We explicitly DO NOT load chunks here to prevent OOM errors on Vercel SSG process
    const sorted = posts.sort((a, b) => {
      const dateA = a.post_timestamp || new Date(a.updated_at || a.created_at || 0).getTime();
      const dateB = b.post_timestamp || new Date(b.updated_at || b.created_at || 0).getTime();
      return dateB - dateA;
    });
    setLocalAdminCache('posts', sorted);
    return sorted;
  } catch (error) {
    handleFirestoreError(error, OperationType.LIST, 'posts');
    return [];
  }
};

export const getPostBySlug = async (slug: string): Promise<Record<string, any> | null> => {
  try {
    const q = query(collection(db, 'posts'), where('slug', '==', slug));
    const snap = await getDocs(q);
    if (!snap.empty) {
      const d = snap.docs[0];
      const data = { id: d.id, ...d.data() };
      await loadChunksForPost(d.id, data);
      return data;
    }
    const docRef = doc(db, 'posts', slug);
    const docSnap = await getDoc(docRef);
    if (docSnap.exists()) {
      const data = { id: docSnap.id, ...docSnap.data() };
      await loadChunksForPost(docSnap.id, data);
      return data;
    }
    return null;
  } catch (error) {
    handleFirestoreError(error, OperationType.GET, `posts/${slug}`);
    return null;
  }
};

